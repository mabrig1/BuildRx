export const RELEASE_GATES = [
  "A real end-to-end user workflow is demonstrated on persisted data.",
  "Generated source passes dependency installation, typecheck, tests and build in a clean runner.",
  "Secrets, auth, ownership and least privilege are independently reviewed.",
  "Production migration, external Git push, cloud deploy and paid resource creation each require an explicit owner action.",
  "Usage analytics are privacy-reviewed; raw project prompts and secret values are never exported to analytics.",
  "A release has rollback instructions, observable health and a reproducible evidence record.",
] as const;

function line(text: string): string {
  return text.replace(/\r?\n/g, " ").replace(/\|/g, "\\|").trim().slice(0, 320);
}

/** Deterministic, reviewable work contract saved with each generated app. */
export function renderSdlcBlueprint(
  plan: AppPlan,
  spec?: FounderOpsSpec,
  founderOpsSource: "agent" | "deterministic" = "deterministic"
): string {
  const journeys = plan.workflows?.slice(0, 6) ?? [];
  const acceptance = (spec?.acceptanceCriteria ?? plan.acceptanceCriteria ?? []).slice(0, 12);
  const cloudRoles = spec?.infrastructure ?? [];

  return [
    "# Product-to-production workflow",
    "",
    "Generated by BuildRx from the current project plan. This is an implementation",
    "and human review contract, **not** proof that any provider is connected or deployed.",
    "",
    `## Product: ${line(plan.appName)}`,
    line(plan.summary),
    "",
    "## Roles and handoffs",
    ...SDLC_ROLES.map((role) =>
      `- **${role.name}** (${role.stages.join(" → ") || "post-release"}): ${role.handoff}.`
    ),
    "",
    "## Work tracks",
    "The video illustrates parallel specialist subagents. BuildRx currently executes",
    "its eleven agents **sequentially**, to preserve a single deterministic virtual",
    "filesystem and avoid conflicting edits. The tracks below are parallel-ready",
    "contracts; their execution is not represented as concurrent.",
    ...IMPLEMENTATION_TRACKS.map((track) =>
      `- **${track.id}** — after ${track.dependsOn.join(", ")}: ${track.output}.`
    ),
    "",
    "## User journeys",
    ...(journeys.length > 0
      ? journeys.map((journey) =>
          `- **${line(journey.name)}** (${line(journey.actor)}): ${line(journey.outcome)}.`
        )
      : ["- Validate the primary user workflow from form entry to saved result."]),
    "",
    "## Acceptance criteria",
    ...(acceptance.length
      ? acceptance.map((criterion) => `- [ ] ${line(criterion)}`)
      : ["- [ ] The primary workflow persists its result and survives a reload."]),
    "",
    "## External service ownership",
    ...(cloudRoles.length
      ? cloudRoles.map((entry) =>
          `- ${entry.provider} (${entry.required ? "required" : "optional"}): ${line(entry.responsibility)}.`
        )
      : ["- Default: use existing BuildRx configured services; no new cloud account is required."]),
    "",
    "## MCP / design / analytics integration boundaries",
    "- Design input (such as Figma) is a **read-only, owner-approved import** until implemented and connected.",
    "- Cloud API discovery and documentation can inform a build but cannot change IAM or provision resources.",
    "- Product feedback is stored owner-scoped and can be included in the next build only at the user's request.",
    "- BigQuery is **not configured** here; existing first-party analytics remain the default.",
    "- Model prompts, tokens, provider keys and generated private data are excluded from analytics.",
    "",
    "## Human-reviewed release gates",
    ...RELEASE_GATES.map((gate) => `- [ ] ${gate}`),
    ...(spec?.humanApprovals ?? []).slice(0, 8).map((gate) => `- [ ] ${line(gate)}`),
    "",
    "## Evidence / limitations",
    `- FounderOps boundary source: ${founderOpsSource}.`,
    "- Static checks are not equivalent to a successful clean build or device test.",
    "- A preview saved by the BuildRx deployment agent is **not** a provider production deployment.",
    "- External deployments, payments, migrations and credential changes are never authorized by this document.",
    "- When a release gate is unverified, report it as unverified; do not silently mark production-ready.",
    "",
  ].join("\n");
}
